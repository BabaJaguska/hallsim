def _round_sig(x, n=4):
    """MATLAB round(x, 4, 'significant')."""
    x = np.asarray(x, dtype=float)
    out = np.zeros_like(x)
    nz = x != 0
    mag = np.floor(np.log10(np.abs(x[nz])))
    out[nz] = np.round(x[nz] / 10 ** (mag - n + 1)) * 10 ** (mag - n + 1)
    return out


